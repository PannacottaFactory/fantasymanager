export const LOG_DICTS: Record<Lang, Record<LogKey, string>> = { en, fr };

export function logT(lang: Lang) {
  const d = LOG_DICTS[lang];
  return (key: LogKey, vars?: Record<string, string | number>) => (vars ? fill(d[key], vars) : d[key]);
}
